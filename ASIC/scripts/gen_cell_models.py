#!/usr/bin/env python3
"""Zero-delay functional Verilog models for the sky130_fd_sc_hd cells used by a netlist.

  gen_cell_models.py <liberty.lib> <netlist.v> <out.v>

The PDK's own Verilog models are built on UDPs, which Verilator cannot read. Every combinational cell
here is `assign out = <liberty function>`; the only sequential cell family supported is the plain
positive-edge D flop (dfxtp), and conb is a tie cell. Anything else in the netlist is an error, so a
resynthesis that starts using e.g. latches or scan flops fails loudly instead of simulating wrongly.
"""
import re, sys

def main(lib_path, net_path, out_path):
    net = open(net_path).read()
    used = sorted(set(re.findall(r'^\s*(sky130_fd_sc_hd__\w+)\s', net, re.M)))
    lib = open(lib_path).read()
    out = ['// Generated by scripts/gen_cell_models.py -- zero-delay functional models (do not edit)',
           '`timescale 1ns/1ps', '`default_nettype none']
    for cell in used:
        m = re.search(r'cell \("%s"\)\s*\{' % re.escape(cell), lib)
        if not m and re.fullmatch(r'sky130_fd_sc_hd__(fill|tapvpwrvgnd)_\d+', cell):
            out.append(f'module {cell}(); endmodule')       # physical-only (routed netlists): no pins, no logic
            continue
        if not m: sys.exit(f'cell {cell} not in liberty')
        nxt = re.search(r'\n\s*cell \("', lib[m.end():])
        body = lib[m.end(): m.end() + (nxt.start() if nxt else len(lib))]
        pins = []                                               # (name, dir, function)
        parts = re.split(r'\n\s*pin \("(\w+)"\)\s*\{', body)
        for i in range(1, len(parts), 2):
            seg = parts[i + 1]
            d = re.search(r'direction : "(\w+)"', seg).group(1)
            f = re.search(r'\bfunction : "([^"]+)"', seg)
            pins.append((parts[i], d, f.group(1) if f else None))
        ins = [p for p, d, _ in pins if d == 'input']; outs = [(p, f) for p, d, f in pins if d == 'output']
        ports = ', '.join(ins + [p for p, _ in outs])
        out.append(f'module {cell}({ports});')
        out += [f'  input {p};' for p in ins] + [f'  output {p};' for p, _ in outs]
        if 'ff ("IQ"' in body:
            if cell.startswith('sky130_fd_sc_hd__dfxtp') and ins == ['CLK', 'D'] or sorted(ins) == ['CLK', 'D']:
                q = outs[0][0]
                out += [f'  reg {q}_r;', f'  always @(posedge CLK) {q}_r <= D;', f'  assign {q} = {q}_r;']
            else: sys.exit(f'unsupported sequential cell {cell} (pins {ins})')
        elif re.search(r'\b(latch|statetable) \(', body): sys.exit(f'unsupported cell {cell}')
        else:
            for p, f in outs:
                if f is None:
                    if 'conb' in cell: out.append(f"  assign {p} = {'1' if p == 'HI' else '0'};"); continue
                    sys.exit(f'{cell}.{p}: no function')
                e = f.replace('!', '~').replace("'", '')
                out.append(f'  assign {p} = {e};')
        out.append('endmodule')
    open(out_path, 'w').write('\n'.join(out) + '\n')
    print(f'{len(used)} cell models -> {out_path}')

if __name__ == '__main__':
    main(*sys.argv[1:4])
