#!/usr/bin/env bash
# Assemble the Caravel user project for simulation and precheck: a pinned checkout of chipfoundry/caravel_user_project
# with mahi-gpu's wrapper RTL (ASIC/caravel/) and the hardened user_project_wrapper views from a CARAVEL=1 run.
#
#   scripts/caravel_setup.sh <run dir>          e.g. flow/runs/caravel_1030_1500 (or "rtl" for RTL views only)
#   CARAVEL_UP=<dir>  checkout location (default ~/eda/caravel/caravel_user_project; cloned if missing)
#
# The wrapper is hardened by this repository's flow (MINI=1 CARAVEL=1 ./run_asic.sh), flat, not by the
# template's openlane/ targets. The template's verify-* and precheck targets then run in the checkout.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
CARAVEL_UP="${CARAVEL_UP:-$HOME/eda/caravel/caravel_user_project}"
UP_REPO=https://github.com/chipfoundry/caravel_user_project.git
UP_COMMIT=b510613cec367828966b37583f9090ac5ddb6491     # main, 2026-04-23 (MPW_TAG CC2509, open_pdks 3e0e31dc)
SRAM=sky130_sram_2kbyte_1rw1r_32x512_8
SRAM_V="${SRAM_MACRO_DIR:-$HOME/Projects/sky130_sram_macros}/$SRAM/$SRAM.v"
TOP=user_project_wrapper

if [ ! -d "$CARAVEL_UP/.git" ]; then
    git clone -q "$UP_REPO" "$CARAVEL_UP"
    git -C "$CARAVEL_UP" checkout -q "$UP_COMMIT"
fi
have="$(git -C "$CARAVEL_UP" rev-parse HEAD)"
[ "$have" = "$UP_COMMIT" ] || echo "WARNING: $CARAVEL_UP is at $have, expected $UP_COMMIT"

# RTL views (Caravel-level RTL simulation): wrapper + the sv2v-converted mini GPU + the OpenRAM behavioural model
cd "$CARAVEL_UP"
cp "$HERE/caravel/verilog/rtl/user_project_wrapper.v" verilog/rtl/
cp "$HERE/../build/test_mini/gpu_asic_converted.v" verilog/rtl/gpu_caravel_top.v
cp "$SRAM_V" "verilog/rtl/$SRAM.v"
cat > verilog/rtl/uprj_netlists.v <<V
// mahi-gpu: generated by ASIC/scripts/caravel_setup.sh
\`include "defines.v"
\`define USE_POWER_PINS
\`ifdef GL
    \`default_nettype wire
    \`include "gl/$TOP.v"
    \`include "$SRAM.v"
\`else
    \`include "$TOP.v"
    \`include "gpu_caravel_top.v"
    \`include "$SRAM.v"
\`endif
V

[ "${1:-rtl}" = "rtl" ] && { echo "RTL views installed in $CARAVEL_UP"; exit 0; }
F="$(cd "$1" && pwd)/final"
for f in "$F/gds/$TOP.gds" "$F/lef/$TOP.lef" "$F/pnl/$TOP.pnl.v" "$F/def/$TOP.def"; do [ -f "$f" ] || { echo "missing $f"; exit 1; }; done
mkdir -p gds lef def verilog/gl spef/multicorner sdf/multicorner lib
cp "$F/gds/$TOP.gds" gds/
cp "$F/lef/$TOP.lef" lef/
cp "$F/def/$TOP.def" def/
cp "$F/pnl/$TOP.pnl.v" "verilog/gl/$TOP.v"
for c in min nom max; do cp "$F/spef/$c/$TOP.$c.spef" "spef/multicorner/$TOP.$c.spef"; done
echo "caravel_user_project ready at $CARAVEL_UP (wrapper views from $1)"
