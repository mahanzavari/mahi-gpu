"""Derive the flat Caravel wrapper config from the mini flow config.

Usage: caravel_config.py IN.yaml OUT.yaml
The whole chip is hardened as one design, user_project_wrapper (caravel/verilog/rtl/user_project_wrapper.v ->
gpu_caravel_top -> gpu_asic_top + the three SRAM macros), with the same flow settings as the signed-off mini
layout plus the fixed Caravel wrapper settings of chipfoundry/caravel_user_project (openlane/user_project_wrapper,
commit b510613): die, pin DEF template, the four power domains with core ring and straps, and Caravel's SDC.
Flat, not macro-first: inside a met1-met4 sub-macro the SRAM power pins (vertical met4) cannot be reached, and
the SRAM macros need the met4/met5 grid the mini layout already uses.
"""
import re, sys

src, out = sys.argv[1:3]
s = open(src).read()

def set_key(key, value):
    global s
    pat = rf'^{key}:.*$'
    assert re.search(pat, s, re.M), key
    s = re.sub(pat, f'{key}: {value}', s, count=1, flags=re.M)

set_key('DESIGN_NAME', '"user_project_wrapper"')
set_key('CLOCK_PORT', '"wb_clk_i"')
set_key('DIE_AREA', '[0, 0, 2920, 3520]')
s = re.sub(r'^CORE_AREA:.*\n', '', s, flags=re.M)                      # derived from the die, as in the template
s = re.sub(r'^(VERILOG_FILES:\s*\n)', r'\1  - "dir::../caravel/verilog/rtl/defines.v"\n'
           r'  - "dir::../caravel/verilog/rtl/user_project_wrapper.v"\n', s, flags=re.M)
for inst in ('mem_inst.pmem.macro', 'mem_inst.dmem.macro', 'gpu_inst.unified_cache.data_eng.g_sram.sram.macro'):
    s = re.sub(r'(?<![\w.])' + re.escape(inst), 'mprj.gpu.' + inst, s)
s = s.replace(' VPWR VGND vccd1 vssd1', ' vccd1 vssd1 vccd1 vssd1')
new = {
    'FP_DEF_TEMPLATE': '"dir::caravel/user_project_wrapper.def"',
    'PNR_SDC_FILE': '"dir::caravel/user_project_wrapper.sdc"',
    'SIGNOFF_SDC_FILE': '"dir::caravel/user_project_wrapper.sdc"',
    'VDD_NETS': '["vccd1", "vccd2", "vdda1", "vdda2"]',
    'GND_NETS': '["vssd1", "vssd2", "vssa1", "vssa2"]',
    'PDN_CORE_RING': 'true',
    'PDN_CORE_RING_VWIDTH': '3.1', 'PDN_CORE_RING_HWIDTH': '3.1',
    'PDN_CORE_RING_VOFFSET': '12.45', 'PDN_CORE_RING_HOFFSET': '12.45',
    'PDN_CORE_RING_VSPACING': '1.7', 'PDN_CORE_RING_HSPACING': '1.7',
    'PDN_VOFFSET': '5', 'PDN_HOFFSET': '5', 'PDN_VWIDTH': '3.1', 'PDN_HWIDTH': '3.1',
    'PDN_VSPACING': '15.5', 'PDN_HSPACING': '15.5', 'PDN_VPITCH': '180', 'PDN_HPITCH': '180',
    'MAGIC_DEF_LABELS': 'false', 'MAGIC_ZEROIZE_ORIGIN': 'false',
}
for key in new:
    assert not re.search(rf'^{key}:', s, re.M), key
s += '\n# --- Caravel user_project_wrapper (generated by scripts/caravel_config.py; values from the template) ---\n'
s += ''.join(f'{k}: {v}\n' for k, v in new.items())
open(out, 'w').write(s)
